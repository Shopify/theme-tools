const answer = (pattern, options) => {
  const mm = new Minimatch(pattern, options);
  return paths.flatMap((f, i) => {
    // minimatch checks a path against the pattern before splitting it, unless it is the path that
    // it checked last. Both ways must give the same answer, or it depends on what came before.
    mm.match('\0');
    const checked = mm.match(f);
    const split = mm.match(f);
    if (checked !== split) {
      throw new Error(`${JSON.stringify(pattern)} ${JSON.stringify(options)} ${JSON.stringify(f)}`);
    }
    return split ? [i] : [];
  });
};

const duplicates = patterns.filter((p, i) => patterns.indexOf(p) !== i);
if (duplicates.length) throw new Error(`duplicate patterns: ${JSON.stringify(duplicates)}`);
const cases = (options) => patterns.map((p) => JSON.stringify([p, answer(p, options)]));
const json = [
  '{',
  `"minimatch": ${JSON.stringify(version)},`,
  `"paths": ${JSON.stringify(paths)},`,
  `"cases": [\n${cases({}).join(',\n')}\n],`,
  `"dotCases": [\n${cases({ dot: true }).join(',\n')}\n]`,
  '}',
  '',
].join('\n');
fs.writeFileSync(path.resolve(__dirname, '..', 'src', 'minimatch.json'), json);
