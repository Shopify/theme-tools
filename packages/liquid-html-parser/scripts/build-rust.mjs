/**
 * Build the Rust parser backend to WASM.
 *
 * Usage: pnpm --dir packages/liquid-html-parser build:rust
 *
 * 1. Checks `wasm-bindgen --version` equals the `wasm-bindgen` version in
 *    rust/Cargo.lock. The CLI and the crate must match exactly, so a mismatch
 *    fails with the install command.
 * 2. `cargo build --release --target wasm32-unknown-unknown` in rust/.
 * 3. `wasm-bindgen --target web --out-dir rust/pkg`.
 * 4. Writes rust/pkg/bytes.mjs, the `.wasm` as base64, so `register.mjs` can
 *    instantiate synchronously with no fs or fetch.
 * 5. Prints the `.wasm` byte size and writes it to rust/pkg/size.json.
 * 6. Marks rust/pkg/ as ESM with its own package.json.
 */
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RUST_DIR = path.resolve(__dirname, '..', 'rust');
const PKG_DIR = path.join(RUST_DIR, 'pkg');
const CRATE_WASM = path.join(
  RUST_DIR,
  'target',
  'wasm32-unknown-unknown',
  'release',
  'liquid_html_parser.wasm',
);
const BINDGEN_WASM = path.join(PKG_DIR, 'liquid_html_parser_bg.wasm');

checkWasmBindgenVersion();
run('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], RUST_DIR);
run('wasm-bindgen', ['--target', 'web', '--out-dir', PKG_DIR, CRATE_WASM], RUST_DIR);
writeBytesModule();

function checkWasmBindgenVersion() {
  const expected = lockedVersion('wasm-bindgen');
  const installed = installedWasmBindgenVersion();
  if (installed === expected) return;

  console.error(
    `wasm-bindgen CLI ${installed ?? 'not found'} does not match wasm-bindgen ${expected} in rust/Cargo.lock.\n` +
      `Install the matching CLI with:\n\n  cargo install wasm-bindgen-cli --version ${expected} --locked\n`,
  );
  process.exit(1);
}

function lockedVersion(name) {
  const lock = fs.readFileSync(path.join(RUST_DIR, 'Cargo.lock'), 'utf8');
  const match = lock.match(
    new RegExp(`\\[\\[package\\]\\]\\nname = "${name}"\\nversion = "([^"]+)"`),
  );
  if (!match) throw new Error(`rust/Cargo.lock has no entry for ${name}`);
  return match[1];
}

function installedWasmBindgenVersion() {
  try {
    const output = execFileSync('wasm-bindgen', ['--version'], { encoding: 'utf8' });
    return output.trim().replace(/^wasm-bindgen /, '');
  } catch {
    return undefined;
  }
}

function run(command, args, cwd) {
  execFileSync(command, args, { cwd, stdio: 'inherit' });
}

function writeBytesModule() {
  const wasm = fs.readFileSync(BINDGEN_WASM);
  const base64 = wasm.toString('base64');
  fs.writeFileSync(
    path.join(PKG_DIR, 'bytes.mjs'),
    `// Generated by scripts/build-rust.mjs. The parser .wasm as base64.\n` +
      `export default ${JSON.stringify(base64)};\n`,
  );
  fs.writeFileSync(path.join(PKG_DIR, 'size.json'), JSON.stringify({ bytes: wasm.length }) + '\n');
  // The wasm-bindgen glue is ESM, and this package is CommonJS
  fs.writeFileSync(path.join(PKG_DIR, 'package.json'), '{ "type": "module" }\n');
  console.log(`liquid_html_parser_bg.wasm: ${wasm.length} bytes`);
}
